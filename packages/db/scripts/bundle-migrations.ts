// Regenerates src/migrations/migrations.gen.ts from migrations/*.sql, so the
// package needs no filesystem access at runtime (bundlers, edge runtimes).
// Usage: pnpm --filter @bebranded/elearning-db db:bundle [--verify]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { readMigrationFiles } from "../tests/support/migration-dir.js";

const outFile = fileURLToPath(new URL("../src/migrations/migrations.gen.ts", import.meta.url));
const files = readMigrationFiles(new URL("../migrations/", import.meta.url));
const body = files
  .map(
    (file) =>
      `  {\n    name: ${JSON.stringify(file.name)},\n    sql: ${JSON.stringify(file.sql)},\n  },`,
  )
  .join("\n");
const output = `// Generated by scripts/bundle-migrations.ts from migrations/*.sql. Do not edit.\n// Size limits do not apply to generated files (languages/typescript).\n\nexport const BUNDLED_MIGRATIONS: readonly { readonly name: string; readonly sql: string }[] = [\n${body}\n];\n`;

if (process.argv.includes("--verify")) {
  if (readFileSync(outFile, "utf8") !== output) {
    process.stderr.write("migrations.gen.ts is out of date: run db:bundle\n");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outFile, output);
}
