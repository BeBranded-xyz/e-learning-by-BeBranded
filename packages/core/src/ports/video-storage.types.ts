import type { LearnerId, LessonId, VideoAssetId } from "../content/ids.js";
import type { VideoProgressState } from "../video/heartbeat.js";
import type { VideoAssetStatus } from "../video/video.schemas.js";
import type { TenantScope } from "./storage.types.js";
import type { VideoWebhookEvent } from "./video-provider.types.js";

export type VideoCaption = { readonly lang: string; readonly url: string };

export type VideoAsset = {
  readonly id: VideoAssetId;
  readonly lessonId: LessonId;
  /** `VideoProvider.name` of the provider hosting the file. */
  readonly provider: string;
  /** The provider's identifier of the asset. */
  readonly providerAssetId: string;
  readonly status: VideoAssetStatus;
  readonly durationSeconds: number | null;
  readonly thumbnailUrl: string | null;
  readonly captions: readonly VideoCaption[];
};

export type VideoProgress = VideoProgressState & {
  readonly lessonId: LessonId;
  readonly learnerId: LearnerId;
  readonly watchedSeconds: number;
  /** Between 0 and 1. */
  readonly coverage: number;
};

export type VideoHeartbeatKey = {
  readonly lessonId: LessonId;
  readonly learnerId: LearnerId;
  /** Generated by the player, one per player load. */
  readonly sessionId: string;
  readonly seq: number;
};

export type VideoStorageReads = {
  findVideoAsset(scope: TenantScope, lessonId: LessonId): Promise<VideoAsset | null>;
  findVideoProgress(
    scope: TenantScope,
    learnerId: LearnerId,
    lessonId: LessonId,
  ): Promise<VideoProgress | null>;
};

export type VideoStorageWrites = {
  /**
   * Creates or replaces the video of a lesson the tenant owns. False when the
   * lesson does not exist or belongs to another tenant.
   */
  saveVideoAsset(scope: TenantScope, asset: VideoAsset): Promise<boolean>;
  /**
   * Applies a verified provider webhook. Not tenant-scoped: the provider's
   * signature authenticates the call and the asset id selects the row. Null
   * when the module has no such asset, or when a late `uploading` or
   * `processing` event would move a ready asset back.
   */
  applyVideoWebhook(provider: string, event: VideoWebhookEvent): Promise<VideoAsset | null>;
  /**
   * Records `seq` for the player session and returns true only when it is
   * newer than every `seq` already received for that session, so replayed
   * heartbeats are ignored. False too when the lesson was not started.
   */
  acceptVideoHeartbeat(scope: TenantScope, key: VideoHeartbeatKey): Promise<boolean>;
  /**
   * Returns the learner's video progress, created empty when missing, locked
   * until the transaction ends. Null when the lesson was not started.
   */
  lockOrCreateVideoProgress(
    scope: TenantScope,
    learnerId: LearnerId,
    lessonId: LessonId,
  ): Promise<VideoProgress | null>;
  saveVideoProgress(scope: TenantScope, progress: VideoProgress): Promise<void>;
};
